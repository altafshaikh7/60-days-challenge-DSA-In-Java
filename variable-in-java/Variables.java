public class Variables {
    public static void main(String[] args) {

        int x = 5; // initiolization + declaration
        System.out.println(x);

        int y; // initiolization
        y = 10; // declaration
        System.out.println(y);

        int a = 5;
        System.out.println(a);

        a = a + 4;
        System.out.println(a);

        a = a - 2;
        System.out.println(a);

        a = a * 10;
        System.out.println(a);
    }
}