public class divisionofdata {
    public static void main(String[] args) {

        int a = 10; // int and double = double
        double b = 3;

        System.out.println(a / b);

        int c = 10; // int and int = int
        int d = 3;
        System.out.println(c / d);

        int e = 10; // int and double = double
        double f = 3.0;
        System.out.println(e / f);

        double g = 10.0; // double and int = double
        int h = 3;
        System.out.println(g / h);

    }
}
